"""從三份情境檔的職缺名稱中，萃取與職位無關的雜訊文字（供人工檢核）。

七類：地區／分區／職缺編號／招募文字／招募窗口姓名／電話／廠商內部編號
"""
import pandas as pd, re, json
from collections import Counter

FILES = ['1_best_practice.csv', '2_enhancement.csv', '3_worst_practice.csv']
BASE = '/home/user/main/job-classification-kb/training_feedback/'

titles = []
for f in FILES:
    df = pd.read_csv(BASE + f, skiprows=1, dtype=str)
    titles += df['職缺名稱'].dropna().tolist()
titles = list(dict.fromkeys(titles))
print(f"不重複職缺名稱：{len(titles):,}")

CITY = ('台北|臺北|新北|基隆|桃園|新竹|苗栗|台中|臺中|彰化|南投|雲林|嘉義|台南|臺南|高雄|屏東|'
        '宜蘭|花蓮|台東|臺東|澎湖|金門|連江|馬祖|北市|中市|南市|竹市|竹縣')
DISTRICT = ('中正|大同|中山|松山|大安|萬華|信義|士林|北投|內湖|南港|文山|板橋|三重|中和|永和|新莊|'
            '新店|樹林|鶯歌|三峽|淡水|汐止|瑞芳|土城|蘆洲|五股|泰山|林口|深坑|八里|三芝|石門|平溪|'
            '桃園區|中壢|平鎮|八德|楊梅|蘆竹|大溪|龍潭|龜山|大園|觀音|新屋|復興|竹北|竹東|新豐|湖口|'
            '苗栗市|頭份|竹南|後龍|通霄|苑裡|中區|東區|西區|南區|北區|西屯|南屯|北屯|豐原|大里|太平|'
            '清水|沙鹿|梧棲|后里|神岡|潭子|大雅|新社|石岡|外埔|大甲|大安區|烏日|霧峰|烏日|彰化市|員林|'
            '鹿港|和美|溪湖|田中|北斗|二林|斗六|斗南|虎尾|西螺|北港|嘉義市|太保|朴子|新營|鹽水|白河|'
            '柳營|後壁|東山|麻豆|下營|六甲|官田|大內|佳里|學甲|西港|七股|將軍|北門|新化|善化|新市|安定|'
            '山上|玉井|楠西|南化|左鎮|仁德|歸仁|關廟|龍崎|永康|安南|安平|新興|前金|苓雅|鹽埕|鼓山|旗津|'
            '前鎮|三民|楠梓|小港|左營|仁武|大社|岡山|路竹|阿蓮|田寮|燕巢|橋頭|梓官|彌陀|永安|湖內|鳳山|'
            '大寮|林園|鳥松|大樹|旗山|美濃|六龜|甲仙|杉林|內門|茂林|桃源|屏東市|潮州|東港|恆春|竹南')
NAME_SUR = ('陳|林|黃|張|李|王|吳|劉|蔡|楊|許|鄭|謝|郭|洪|曾|邱|廖|賴|周|徐|蘇|葉|莊|呂|江|何|蕭|羅|'
            '高|潘|簡|朱|鍾|游|彭|詹|胡|施|沈|余|盧|梁|趙|顏|柯|翁|魏|孫|戴|范|方|宋|鄧|杜|傅|侯|曹|溫')

PATTERNS = [
    ('1_地區', [
        rf'(?:{CITY})(?:市|縣)?',
    ]),
    ('2_分區', [
        rf'(?:{DISTRICT})(?:區|鄉|鎮|市)?',
        r'[北中南東]部(?:區)?', r'[北中南東]區', r'大[台臺][北中南]',
        r'[^\s（(【\[]{1,6}(?:分公司|分店|門市|廠|營業所|服務處|辦事處)',
        r'[A-Za-z]?\d{0,2}(?:店|廠|館|處)',
    ]),
    ('3_職缺編號', [
        r'(?:No|NO|no)[.．:：\s]*\d+', r'#\d+', r'編號[:：]?\s*\w+',
        r'\b[A-Z]{1,4}[-_]?\d{3,8}\b',
    ]),
    ('4_招募文字', [
        r'急徵|急征|誠徵|誠征|招募|徵才|徵求|求才|熱徵|大徵|快徵|速徵|徵人|應徵|招聘|補人',
        r'電洽|面洽|洽詢|洽談|來電|請洽|意洽|電話洽|預約|可議|面議',
        r'高薪|優薪|month|月薪|時薪|日薪|年薪|獎金|保障|起薪',
        r'免經驗|無經驗|經驗不拘|新手|可培訓|培訓|歡迎|意者|意者請|長期|短期|兼職|全職|正職|工讀',
        r'立即上工|馬上上班|隨到隨上|今日面試|快速面試',
    ]),
    ('5_招募窗口姓名', [
        rf'(?:{NAME_SUR})(?:先生|小姐|經理|主任|課長|襄理|專員|姐|哥|老師|店長|副理|協理)',
        rf'洽\s*(?:{NAME_SUR})[^\s，,。]{{0,3}}',
        rf'聯絡人[:：]?\s*(?:{NAME_SUR})[^\s，,。]{{0,3}}',
    ]),
    ('6_電話', [
        r'0\d{1,3}[-\s]?\d{3,4}[-\s]?\d{3,4}',
        r'09\d{2}[-\s]?\d{3}[-\s]?\d{3}',
        r'\(0\d{1,2}\)\s?\d{3,4}[-\s]?\d{3,4}',
        r'#\s?\d{2,4}(?=\D|$)',
        r'分機\s?\d+',
    ]),
    ('7_廠商內部編號', [
        r'[A-Za-z]{1,5}\d{2,8}[A-Za-z]?',
        r'\d{4,10}',
        r'[（(]\s*[A-Za-z0-9\-_]{2,12}\s*[)）]',
    ]),
]

results = {}
for cat, pats in PATTERNS:
    c = Counter()
    rx = [re.compile(p) for p in pats]
    for t in titles:
        for r in rx:
            for m in r.findall(t):
                m = m.strip() if isinstance(m, str) else m
                if m and len(m) <= 20:
                    c[m] += 1
    results[cat] = c
    print(f"{cat}: {len(c):,} 種不重複片語，總出現 {sum(c.values()):,} 次")

json.dump({k: dict(v.most_common()) for k, v in results.items()},
          open('/home/user/main/job-classification-kb/scripts/_noise_tokens.json', 'w', encoding='utf-8'),
          ensure_ascii=False, indent=1)
print("\n已存 scripts/_noise_tokens.json")
